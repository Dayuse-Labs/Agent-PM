#!/usr/bin/env python3
"""Build what the widget page actually loads from its sources in web/vendor/static.

The sources stay the truth (the JS tests import them, the CSS tests read them)
and stay served, but the page no longer loads them one by one: before this,
each visit fetched ~29 ES modules and 12 stylesheets (an `@import` chain), all
revalidated on every visit. The outputs are COMMITTED, because the `widget`
image is stdlib Python with no build step (web/Dockerfile):

- `dist/chat.js`  — esbuild bundle of `js/chat/index.js` (ESM, minified, no
  syntax lowering: `--target=esnext` keeps exactly what the sources ship);
- `dist/chat.css` — esbuild bundle of `css/chat/index.css` (`@import` inlined,
  minified; `/static/...` URLs left as they are, the proxy versions them);
- `--images`: the hero photos in AVIF and WebP at two widths each, next to
  the original JPEGs, which stay as the fallback;
- `--font`: `MaisonNeueExtended-Bold.woff2`, from the OTF (all glyphs kept).

Each bundle starts with the digest of the sources it was built from;
tests/test_widget_assets.py fails when a source changed without a rebuild.
esbuild is pinned (ESBUILD_VERSION): the one on PATH when it matches, else
`npx --yes esbuild@<version>` (needs the npm registry once).

Usage:
    python3 scripts/build_widget_assets.py              # bundles only
    python3 scripts/build_widget_assets.py --images --font
"""
from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

ESBUILD_VERSION = "0.27.4"

STATIC = Path(__file__).resolve().parent.parent / "web" / "vendor" / "static"
DIST = STATIC / "dist"
JS_ENTRY = Path("js/chat/index.js")
CSS_ENTRY = Path("css/chat/index.css")
SOURCE_DIRS = (Path("js/chat"), Path("css/chat"))

# Hero photos: (source, widths). The sources are 1920x1080 and 1080x1920.
HERO_IMAGES = {
    "hero_usa_desktop.jpg": (1280, 1920),
    "hero_usa_mobile.jpg": (720, 1080),
}
HERO_DIR = Path("hero")
AVIF_QUALITY = 62
WEBP_QUALITY = 80
FONT_OTF = Path("fonts/MaisonNeueExtended-Bold.otf")

_DIGEST_RE = re.compile(r"sources-sha256: ([0-9a-f]{16})")


def source_files(static: Path = STATIC) -> list[Path]:
    """Every file a bundle can be built from, sorted (relative to `static`)."""
    files: list[Path] = []
    for directory in SOURCE_DIRS:
        files += [p.relative_to(static) for p in (static / directory).rglob("*") if p.is_file()]
    return sorted(files, key=lambda p: p.as_posix())


def sources_digest(static: Path = STATIC) -> str:
    digest = hashlib.sha256()
    for rel in source_files(static):
        digest.update(rel.as_posix().encode() + b"\0" + (static / rel).read_bytes() + b"\0")
    return digest.hexdigest()[:16]


def bundle_digest(path: Path) -> str | None:
    """The sources digest recorded in a built bundle's banner, if any."""
    if not path.is_file():
        return None
    match = _DIGEST_RE.search(path.read_text(encoding="utf-8")[:400])
    return match.group(1) if match else None


def _banner(digest: str) -> str:
    return (
        f"/* Generated by scripts/build_widget_assets.py (sources-sha256: {digest}). "
        "Do not edit: change web/vendor/static/{js,css}/chat, then rebuild. */"
    )


def esbuild_command() -> list[str]:
    local = shutil.which("esbuild")
    if local:
        version = subprocess.run([local, "--version"], capture_output=True, text=True).stdout.strip()
        if version == ESBUILD_VERSION:
            return [local]
    return ["npx", "--yes", f"esbuild@{ESBUILD_VERSION}"]


def build_bundles(out_dir: Path = DIST, static: Path = STATIC) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    banner = _banner(sources_digest(static))
    esbuild = esbuild_command()
    common = ["--bundle", "--minify", "--sourcemap=linked", "--sources-content=false", "--log-level=warning"]
    subprocess.run(
        [*esbuild, str(static / JS_ENTRY), *common, "--format=esm", "--target=esnext",
         f"--banner:js={banner}", f"--outfile={out_dir / 'chat.js'}"],
        check=True,
    )
    subprocess.run(
        [*esbuild, str(static / CSS_ENTRY), *common, "--external:/static/*",
         f"--banner:css={banner}", f"--outfile={out_dir / 'chat.css'}"],
        check=True,
    )


def hero_variant(source: str, width: int, ext: str) -> Path:
    return HERO_DIR / f"{Path(source).stem}-{width}.{ext}"


def build_images(static: Path = STATIC) -> None:
    magick = shutil.which("magick")
    if not magick:
        raise SystemExit("build_widget_assets: ImageMagick (`magick`, with AVIF) is required for --images")
    (static / HERO_DIR).mkdir(exist_ok=True)
    for source, widths in HERO_IMAGES.items():
        for width in widths:
            for ext, options in (
                ("avif", ["-quality", str(AVIF_QUALITY)]),
                ("webp", ["-quality", str(WEBP_QUALITY), "-define", "webp:method=6"]),
            ):
                subprocess.run(
                    [magick, str(static / source), "-strip", "-resize", f"{width}x", *options,
                     str(static / hero_variant(source, width, ext))],
                    check=True,
                )


def build_font(static: Path = STATIC) -> None:
    from fontTools.ttLib import TTFont  # needs fonttools + brotli; only for --font

    font = TTFont(str(static / FONT_OTF))
    font.flavor = "woff2"
    font.save(str((static / FONT_OTF).with_suffix(".woff2")))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--images", action="store_true", help="re-encode the hero photos (AVIF/WebP)")
    parser.add_argument("--font", action="store_true", help="re-encode the display font as WOFF2")
    args = parser.parse_args()
    build_bundles()
    if args.images:
        build_images()
    if args.font:
        build_font()
    print(f"build_widget_assets: bundles at {DIST} (sources-sha256: {sources_digest()})", file=sys.stderr)


if __name__ == "__main__":
    main()
